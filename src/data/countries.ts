/** Bandera emoji a partir del código ISO 3166-1 alpha-2 (ej. "ES" → 🇪🇸). */
export function flagOf(code: string): string {
  return String.fromCodePoint(...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))
}

